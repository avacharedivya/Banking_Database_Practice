use banking;
SELECT SUM(BALANCE) FROM ACCOUNTS;
SELECT ACCOUNT_TYPE,SUM(BALANCE)
FROM ACCOUNTS
GROUP BY ACCOUNT_TYPE;

SELECT ACCOUNT_TYPE,AVG(BALANCE),COUNT(ACC_ID)
FROM ACCOUNTS
GROUP BY ACCOUNT_TYPE;

SELECT ACCOUNT_TYPE,ROUND(AVG(BALANCE)),COUNT(ACC_ID)
FROM ACCOUNTS
GROUP BY ACCOUNT_TYPE;


SELECT ACC_ID,ACCOUNT_TYPE,BALANCE,AVG(BALANCE)
OVER(PARTITION BY ACCOUNT_TYPE) AS AVERAGE FROM ACCOUNTS;

SELECT ACC_ID,ACCOUNT_TYPE,BALANCE,RANK()
OVER(partition by  ACCOUNT_TYPE ORDER BY BALANCE DESC) AS RNK
FROM ACCOUNTS;

select TRANSACTION_ID,TRANSACTION_DATE,TRANSACTION_TYPE,AMOUNT,SUM(AMOUNT)
OVER(ORDER BY TRANSACTION_DATE) AS RUNNING_TOTAL
FROM TRANSACTIONS;

SELECT * FROM TRANSACTIONS;
SELECT ACC_ID,TRANSACTION_ID,TRANSACTION_TYPE,AMOUNT,row_number()
OVER(partition by TRSNSACTION_TYPE)
FROM TRANSACTIONS;
